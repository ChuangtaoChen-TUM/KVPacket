"""Parse the XML-delimited function-call syntax used by Qwen chat templates."""

from __future__ import annotations

import json
import re
from collections.abc import Mapping
from hashlib import sha256

from ..types import ToolCall

__all__ = ["QwenToolCallParser"]

_OPEN = "<tool_call>"
_TOOL_CALL = re.compile(r"<tool_call>\s*(.*?)\s*</tool_call>", re.DOTALL)


class QwenToolCallParser:
    """Extract one or more Qwen JSON function calls from decoded assistant text.

    Qwen emits calls as ``<tool_call>{...}</tool_call>``. Call IDs are not always
    generated by the model, so missing IDs are derived deterministically from the raw
    call and its output order. This keeps final parsing and repeated streaming checks
    stable.
    """

    def parse(self, text: str) -> tuple[str, tuple[ToolCall, ...]]:
        """Remove complete tool blocks and convert their JSON payloads."""
        calls: list[ToolCall] = []
        for index, match in enumerate(_TOOL_CALL.finditer(text)):
            raw = match.group(1)
            try:
                value = json.loads(raw)
            except json.JSONDecodeError as error:
                raise ValueError("Qwen emitted an invalid tool-call JSON object") from error
            if not isinstance(value, Mapping):
                raise ValueError("Qwen tool-call payload must be a JSON object")
            name = value.get("name")
            if not isinstance(name, str) or not name:
                raise ValueError("Qwen tool-call payload requires a non-empty name")
            arguments = value.get("arguments", {})
            if isinstance(arguments, str):
                try:
                    arguments = json.loads(arguments)
                except json.JSONDecodeError as error:
                    raise ValueError("Qwen tool-call arguments are not valid JSON") from error
            if not isinstance(arguments, Mapping):
                raise ValueError("Qwen tool-call arguments must be a JSON object")
            supplied_id = value.get("id")
            if isinstance(supplied_id, str) and supplied_id:
                call_id = supplied_id
            else:
                digest = sha256(f"{index}:{raw}".encode()).hexdigest()[:24]
                call_id = f"call_{digest}"
            calls.append(
                ToolCall(
                    call_id=call_id,
                    name=name,
                    arguments={str(key): item for key, item in arguments.items()},
                )
            )
        if not calls:
            return text.strip(), ()
        content = _TOOL_CALL.sub("", text).strip()
        return content, tuple(calls)

    def visible_text_prefix(self, text: str) -> str:
        """Expose a normalized prefix before the first possible tool marker.

        Leading whitespace is removed and trailing whitespace is withheld until later
        visible text makes it internal. Applying the same normalization in ``parse``
        keeps streamed text append-only when a later tool block is removed.
        """
        marker_start = text.find(_OPEN)
        if marker_start >= 0:
            return text[:marker_start].strip()
        max_partial = min(len(text), len(_OPEN) - 1)
        for length in range(max_partial, 0, -1):
            if _OPEN.startswith(text[-length:]):
                return text[:-length].strip()
        return text.strip()
